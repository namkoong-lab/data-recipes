#!/usr/bin/env python3
"""
Script to load an OLMo model from a checkpoint directory generated by train.py

This script can load models from both sharded and unsharded checkpoints.
"""

import argparse
import logging
import sys
from pathlib import Path
from typing import Optional

import torch
import torch.nn as nn
from torch.distributed.fsdp import FullyShardedDataParallel as FSDP

from olmo.checkpoint import Checkpointer, FullCheckpointer, load_state_dict

# Import OLMo modules
from olmo.config import ModelConfig, TrainConfig
from olmo.model import OLMo
from olmo.util import find_latest_checkpoint

logging.basicConfig(level=logging.INFO)
log = logging.getLogger(__name__)


def load_model_from_checkpoint(
    checkpoint_path: str, device: str = "cpu", load_optimizer_state: bool = False, load_trainer_state: bool = False
) -> tuple[OLMo, Optional[dict], Optional[dict]]:
    """
    Load an OLMo model from a checkpoint directory.

    Args:
        checkpoint_path: Path to the checkpoint directory
        device: Device to load the model on ('cpu', 'cuda', 'auto')
        load_optimizer_state: Whether to load optimizer state
        load_trainer_state: Whether to load trainer state

    Returns:
        Tuple of (model, optimizer_state, trainer_state)
    """
    checkpoint_path = Path(checkpoint_path)

    if not checkpoint_path.exists():
        raise FileNotFoundError(f"Checkpoint path does not exist: {checkpoint_path}")

    # Handle device selection
    if device == "auto":
        device = "cuda" if torch.cuda.is_available() else "cpu"

    log.info(f"Loading model from checkpoint: {checkpoint_path}")
    log.info(f"Target device: {device}")

    # Try to load config from checkpoint directory
    config_path = checkpoint_path / "config.yaml"
    if config_path.exists():
        log.info(f"Loading config from: {config_path}")
        config = TrainConfig.load(config_path)
        model_config = config.model
    else:
        log.warning("No config.yaml found in checkpoint directory. You may need to provide model config manually.")
        # Create a default model config - you may need to adjust this based on your model
        model_config = ModelConfig()

    # Initialize the model
    log.info("Initializing model...")
    model = OLMo(model_config)
    log.info(f"Model initialized with {model.num_params():,d} parameters")

    # Load model state dict
    try:
        # First try to load as unsharded checkpoint (model.pt)
        model_state_path = checkpoint_path / "model.pt"
        if model_state_path.exists():
            log.info("Loading unsharded model state...")
            model_state = torch.load(model_state_path, map_location=device)
            model.load_state_dict(model_state, strict=True)
        else:
            # Try to load as sharded checkpoint
            log.info("Attempting to load sharded model state...")
            try:
                # Use OLMo's built-in checkpoint loading
                checkpointer = FullCheckpointer(config if "config" in locals() else None)
                model_state = load_state_dict(checkpoint_path, "model.pt", map_location=device)
                model.load_state_dict(model_state, strict=True)
            except Exception as e:
                log.error(f"Failed to load sharded checkpoint: {e}")
                raise

    except Exception as e:
        log.error(f"Failed to load model state: {e}")
        raise

    # Move model to target device
    model = model.to(device)
    log.info(f"Model loaded and moved to {device}")

    # Load optimizer state if requested
    optimizer_state = None
    if load_optimizer_state:
        try:
            optim_path = checkpoint_path / "optim.pt"
            if optim_path.exists():
                log.info("Loading optimizer state...")
                optimizer_state = torch.load(optim_path, map_location=device)
            else:
                optimizer_state = load_state_dict(checkpoint_path, "optim.pt", map_location=device)
        except Exception as e:
            log.warning(f"Failed to load optimizer state: {e}")

    # Load trainer state if requested
    trainer_state = None
    if load_trainer_state:
        try:
            # Try different possible trainer state files
            for train_file in ["train.pt", "other.pt"]:
                try:
                    trainer_state = load_state_dict(checkpoint_path, train_file)
                    log.info(f"Loaded trainer state from {train_file}")
                    break
                except:
                    continue
        except Exception as e:
            log.warning(f"Failed to load trainer state: {e}")

    return model, optimizer_state, trainer_state


def load_latest_checkpoint(
    checkpoint_dir: str, device: str = "auto", load_optimizer_state: bool = False, load_trainer_state: bool = False
) -> tuple[OLMo, Optional[dict], Optional[dict]]:
    """
    Load the latest checkpoint from a directory containing multiple checkpoints.

    Args:
        checkpoint_dir: Directory containing checkpoint subdirectories
        device: Device to load the model on
        load_optimizer_state: Whether to load optimizer state
        load_trainer_state: Whether to load trainer state

    Returns:
        Tuple of (model, optimizer_state, trainer_state)
    """
    latest_checkpoint = find_latest_checkpoint(checkpoint_dir)
    if latest_checkpoint is None:
        raise FileNotFoundError(f"No checkpoints found in {checkpoint_dir}")

    log.info(f"Latest checkpoint found: {latest_checkpoint}")
    return load_model_from_checkpoint(
        str(latest_checkpoint),
        device=device,
        load_optimizer_state=load_optimizer_state,
        load_trainer_state=load_trainer_state,
    )


def main():
    parser = argparse.ArgumentParser(description="Load an OLMo model from checkpoint")
    parser.add_argument("checkpoint_path", help="Path to checkpoint directory or parent directory")
    parser.add_argument(
        "--device", choices=["cpu", "cuda", "auto"], default="auto", help="Device to load model on"
    )
    parser.add_argument("--latest", action="store_true", help="Load latest checkpoint from directory")
    parser.add_argument("--load-optimizer", action="store_true", help="Also load optimizer state")
    parser.add_argument("--load-trainer", action="store_true", help="Also load trainer state")
    parser.add_argument("--test-forward", action="store_true", help="Test forward pass with dummy input")

    args = parser.parse_args()

    try:
        if args.latest:
            model, optimizer_state, trainer_state = load_latest_checkpoint(
                args.checkpoint_path,
                device=args.device,
                load_optimizer_state=args.load_optimizer,
                load_trainer_state=args.load_trainer,
            )
        else:
            model, optimizer_state, trainer_state = load_model_from_checkpoint(
                args.checkpoint_path,
                device=args.device,
                load_optimizer_state=args.load_optimizer,
                load_trainer_state=args.load_trainer,
            )

        log.info("✓ Model loaded successfully!")
        log.info(f"Model has {model.num_params():,d} total parameters")
        log.info(f"Model has {model.num_params(include_embedding=False):,d} non-embedding parameters")

        if optimizer_state:
            log.info("✓ Optimizer state loaded")

        if trainer_state:
            log.info("✓ Trainer state loaded")
            if "global_step" in trainer_state:
                log.info(f"Global step: {trainer_state['global_step']}")
            if "global_data_step" in trainer_state:
                log.info(f"Global data step: {trainer_state['global_data_step']}")

        # Test forward pass if requested
        if args.test_forward:
            log.info("Testing forward pass...")
            model.eval()
            with torch.no_grad():
                # Create dummy input (batch_size=1, seq_len=128)
                device = next(model.parameters()).device
                dummy_input = torch.randint(0, model.config.vocab_size, (1, 128), device=device)

                try:
                    output = model(dummy_input)
                    log.info(f"✓ Forward pass successful! Output shape: {output.logits.shape}")
                except Exception as e:
                    log.error(f"✗ Forward pass failed: {e}")
                    raise

        return model, optimizer_state, trainer_state

    except Exception as e:
        log.error(f"Failed to load model: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()
